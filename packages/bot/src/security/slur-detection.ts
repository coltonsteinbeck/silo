// These common shortened spellings are treated as slur evasions when they are
// generated by the assistant, separated with punctuation, or derived from an
// acronym request. Keeping them separate avoids treating every matching plain
// user token as a direct lexical slur without considering context.
const BLOCKED_SLUR_VARIANTS = ['nigga', 'niga', 'fag'] as const;

const ALL_BLOCKED_FORMS = [...BLOCKED_SLUR_TOKENS, ...BLOCKED_SLUR_VARIANTS];
const BLOCKED_FORM_SET = new Set<string>(ALL_BLOCKED_FORMS);
const MIN_INITIALISM_LENGTH = Math.min(...ALL_BLOCKED_FORMS.map(token => token.length));
const MAX_INITIALISM_LENGTH = Math.max(...ALL_BLOCKED_FORMS.map(token => token.length));

